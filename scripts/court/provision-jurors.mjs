/**
 * `provision-jurors` — put a STABLE ceremony identity on each juror box.
 *
 * The ceremony generates a fresh key per box per run by default. That is right
 * for a transport test and wrong for a bond: a bond is funded to a PUBLIC key,
 * so the key must exist BEFORE the money moves and must survive every later run.
 * This helper creates that key **on the box** (never here), at
 *
 *   <dir>/juror-<idx>.sec        mode 0600, outside the repo
 *
 * and prints only `idx → <x-only pubkey>`. Nothing secret crosses the network in
 * either direction: the key is generated by the box's own CSPRNG and never
 * leaves it. What the operator carries away is a public key — the thing a bond
 * is funded to.
 *
 * No dependencies on the box: key generation uses `node:crypto`'s built-in
 * secp256k1 ECDH, so this works on a box that has Node and nothing else (the
 * juror bundle is self-contained and the boxes carry no `node_modules`).
 *
 * EVEN-Y ONLY (`BOND_KEY_NOT_XONLY_LIFTABLE`). The court⊕juror bond script is
 * P2WSH over `OP_2 <court> <juror> OP_2 OP_CHECKMULTISIG`, and a BIP-340 x-only
 * key is lifted to the even-Y point. If the juror's real key is ODD-Y the script
 * commits to a curve point the key cannot sign for: the bond looks like
 * collateral and can never be slashed (measured on the host round — Core
 * rejects the 2-of-2 witness with NULLFAIL). So:
 *   - a GENERATED key is rejected and regenerated until it is even-Y;
 *   - an EXISTING key that is odd-Y is REFUSED, never replaced — a bond may
 *     already be funded to it, and replacing it would strand that bond.
 *
 * Idempotent: an existing, even-Y key is kept and only its public key printed,
 * so re-provisioning can never invalidate a bond.
 *
 * Usage:
 *   node scripts/court/provision-jurors.mjs                # all three boxes
 *   node scripts/court/provision-jurors.mjs --check        # print pubkeys, change nothing
 *   node scripts/court/provision-jurors.mjs --dir=/home/bob/.bao-court/jurors
 *   node scripts/court/provision-jurors.mjs --boxes=vps16gb,bao8gb --json
 */

import { spawnSync } from 'node:child_process';

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function arg(name, fallback) {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
}
const flag = (name) => process.argv.includes(`--${name}`);

const boxes = arg('boxes', 'vps16gb,bao8gb,bao-testnet').split(',').map((b) => b.trim()).filter(Boolean);
/**
 * Outside the repo on purpose: a juror key is not a build artifact. The default
 * is resolved ON EACH BOX as `$HOME/.bao-court/jurors` — the boxes do not share
 * a username (root on vps16gb/bao8gb, `deploy` on bao-testnet), so a fixed
 * absolute path would put the key somewhere unwritable or, worse, somewhere a
 * different run would not look.
 */
const keyDirOverride = arg('dir', '');
const KEY_SUFFIX = '.bao-court/jurors';
const checkOnly = flag('check');
const jsonOut = flag('json');

const SSH = ['-o', 'BatchMode=yes', '-o', 'ConnectTimeout=12', '-o', 'LogLevel=ERROR'];
function nodeFor(box) {
  return box === 'bao-testnet' ? '/opt/bao-court-node/bin/node' : '/usr/bin/node';
}

/**
 * The box-side program, run by the box's own Node from a 0600 temp file that is
 * deleted immediately. It reads or creates the key and prints ONE JSON line:
 * `{ok:true,pubkey,created}` or `{ok:false,reason,detail}`. It never prints the
 * secret, and the secret is never transmitted anywhere.
 *
 * `mode:'check'` refuses to create; `mode:'generate'` creates only if absent.
 * There is deliberately no "replace" mode: replacing a provisioned key would
 * invalidate any bond already funded to it.
 */
function boxScript(path, mode) {
  return `
const crypto = require('node:crypto');
const fs = require('node:fs');
const pathMod = require('node:path');
const path = ${JSON.stringify(path)};
const mode = ${JSON.stringify(mode)};
const out = (o) => { process.stdout.write(JSON.stringify(o) + '\\n'); };

/** compressed pubkey (02|03 ‖ x) for a 32-byte scalar, or null if invalid. */
function pubkey(sec) {
  try {
    const ecdh = crypto.createECDH('secp256k1');
    ecdh.setPrivateKey(sec);
    return ecdh.getPublicKey(undefined, 'compressed');
  } catch { return null; }
}
function xonly(pub) { return pub.subarray(1).toString('hex'); }
function evenY(pub) { return pub[0] === 0x02; }

if (fs.existsSync(path)) {
  const raw = fs.readFileSync(path, 'utf8').trim().toLowerCase();
  if (!/^[0-9a-f]{64}$/.test(raw)) {
    out({ ok: false, reason: 'JUROR_KEY_MALFORMED', detail: 'file is not 64 hex characters' });
    process.exit(2);
  }
  const pub = pubkey(Buffer.from(raw, 'hex'));
  if (!pub) {
    out({ ok: false, reason: 'JUROR_KEY_MALFORMED', detail: 'file is not a valid secp256k1 scalar' });
    process.exit(2);
  }
  if (!evenY(pub)) {
    out({ ok: false, reason: 'BOND_KEY_NOT_XONLY_LIFTABLE',
      detail: 'the existing key is ODD-Y: an x-only bond script would commit to another curve point and the bond could never be spent. Refusing to replace it (a bond may already be funded to it).' });
    process.exit(2);
  }
  out({ ok: true, pubkey: xonly(pub), created: false });
  process.exit(0);
}
if (mode === 'check') {
  out({ ok: false, reason: 'JUROR_KEY_MISSING', detail: 'no provisioned key at ' + path });
  process.exit(2);
}
fs.mkdirSync(pathMod.dirname(path), { recursive: true, mode: 0o700 });
let sec = null;
let pub = null;
let attempts = 0;
do {
  sec = crypto.randomBytes(32);
  pub = pubkey(sec);
  attempts += 1;
  if (attempts > 64) {
    out({ ok: false, reason: 'CSPRNG_UNAVAILABLE', detail: 'no even-Y key in 64 attempts' });
    process.exit(2);
  }
} while (!pub || !evenY(pub));
fs.writeFileSync(path, sec.toString('hex') + '\\n', { mode: 0o600 });
fs.chmodSync(path, 0o600);
out({ ok: true, pubkey: xonly(pub), created: true, attempts });
`;
}

// ---------------------------------------------------------------------------

const results = [];
let failures = 0;

for (const [i, box] of boxes.entries()) {
  const idx = i + 1;
  // Resolve the key directory ON the box (per-box $HOME unless --dir=).
  const homeProbe = spawnSync('ssh', [...SSH, box, 'echo $HOME'], { encoding: 'utf8', timeout: 30000 });
  const home = (homeProbe.stdout ?? '').trim();
  if (homeProbe.status !== 0 || !home.startsWith('/')) {
    failures += 1;
    results.push({ idx, box, ok: false, reason: 'BOX_UNREACHABLE', detail: (homeProbe.stderr ?? '').trim().slice(0, 160) });
    continue;
  }
  const keyDir = keyDirOverride === '' ? `${home}/${KEY_SUFFIX}` : keyDirOverride;
  const path = `${keyDir}/juror-${idx}.sec`;
  const scriptPath = `${keyDir}/.provision-${idx}.cjs`;
  const prep = spawnSync('ssh', [...SSH, box, `mkdir -p ${keyDir} && chmod 700 ${keyDir} && echo ok`], {
    encoding: 'utf8',
    timeout: 30000,
  });
  if (prep.status !== 0) {
    failures += 1;
    results.push({ idx, box, ok: false, reason: 'BOX_UNREACHABLE', detail: (prep.stderr ?? '').trim().slice(0, 160) });
    continue;
  }
  const remote = `cat > ${scriptPath} && chmod 600 ${scriptPath} && ${nodeFor(box)} ${scriptPath}; `
    + `rc=$?; rm -f ${scriptPath}; exit $rc`;
  const r = spawnSync('ssh', [...SSH, box, remote], {
    encoding: 'utf8',
    timeout: 60000,
    input: boxScript(path, checkOnly ? 'check' : 'generate'),
  });
  let parsed = null;
  try {
    parsed = JSON.parse((r.stdout ?? '').trim().split('\n').filter(Boolean).pop() ?? '');
  } catch {
    parsed = null;
  }
  if (r.status === 0 && parsed?.ok) {
    results.push({ idx, box, ok: true, path, pubkey: parsed.pubkey, created: Boolean(parsed.created) });
  } else {
    failures += 1;
    results.push({
      idx,
      box,
      ok: false,
      path,
      reason: parsed?.reason ?? 'PROVISION_FAILED',
      detail: parsed?.detail ?? (r.stderr ?? '').trim().slice(0, 200),
    });
  }
}

if (jsonOut) {
  console.log(JSON.stringify({
    keyDir: keyDirOverride === '' ? `$HOME/${KEY_SUFFIX}` : keyDirOverride,
    checkOnly,
    results,
    ok: failures === 0,
  }, null, 2));
} else {
  console.log(`juror identities on ${boxes.length} box(es)${checkOnly ? ' (check only)' : ''}`
    + ` (${keyDirOverride === '' ? `$HOME/${KEY_SUFFIX}` : keyDirOverride})`);
  for (const r of results) {
    if (r.ok) {
      console.log(`  ${r.idx} → ${r.pubkey}  (${r.box}${r.created ? ', created' : ', existing'})`);
    } else {
      console.log(`  ${r.idx} → BLOCKED ${r.reason} (${r.box}) ${r.detail ?? ''}`);
    }
  }
}
process.exit(failures === 0 ? 0 : 2);
